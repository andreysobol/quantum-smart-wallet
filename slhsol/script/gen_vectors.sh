#!/usr/bin/env bash
# Generate fresh SLH-DSA-SHA2-128s keys, messages and signatures with the Rust
# `rslh` CLI and write them as Solidity constants to test/Vectors.sol.
# Usage: script/gen_vectors.sh
set -euo pipefail
HERE=$(cd "$(dirname "$0")/.." && pwd)
RSLH="$HERE/../rslh"
command -v cargo >/dev/null || PATH="$HOME/.cargo/bin:$PATH"
(cd "$RSLH" && cargo build --release --quiet --bin rslh)
BIN="$RSLH/target/release/rslh"
W=$(mktemp -d); trap 'rm -rf "$W"' EXIT
hex() { od -An -v -tx1 "$1" | tr -d ' \n'; }

# name | message | context | sign mode
CASES=(
  "Hello|hello from rslh|app|--deterministic"
  "Hedged|transfer 100 tokens to 0xBEEF|wallet-v1|"
  "Empty|||--deterministic"
  "Long|$(head -c 300 /dev/urandom | od -An -v -tx1 | tr -d ' \n')|$(printf 'c%.0s' $(seq 255))|"
)

OUT="$HERE/test/Vectors.sol"
{
  echo "// SPDX-License-Identifier: MIT"
  echo "// GENERATED by script/gen_vectors.sh with the rslh CLI ($(date -u +%Y-%m-%d)). Do not edit."
  echo "pragma solidity ^0.8.24;"
  echo
  echo "struct Vector {"
  echo "    bytes pk;"
  echo "    bytes message;"
  echo "    bytes ctx;"
  echo "    bytes sig;"
  echo "}"
  echo
  echo "library Vectors {"
  echo "    uint256 internal constant COUNT = ${#CASES[@]};"
  echo
  echo "    function get(uint256 i) internal pure returns (Vector memory) {"
  for i in "${!CASES[@]}"; do echo "        if (i == $i) return ${CASES[$i]%%|*}();"; done
  echo "        revert(\"no such vector\");"
  echo "    }"
  for c in "${CASES[@]}"; do
    IFS='|' read -r name msg ctx mode <<<"$c"
    "$BIN" keygen --sk "$W/$name.key" --pk "$W/$name.pub" >/dev/null 2>&1   # fresh random key
    "$BIN" export --key "$W/$name.pub" --out "$W/$name.pk" >/dev/null 2>&1
    printf '%s' "$msg" > "$W/$name.msg"
    printf '%s' "$ctx" > "$W/$name.ctx"
    "$BIN" sign --sk "$W/$name.key" --in "$W/$name.msg" --sig "$W/$name.sig" --context "$ctx" $mode >/dev/null 2>&1
    "$BIN" verify --pk "$W/$name.pub" --in "$W/$name.msg" --sig "$W/$name.sig" --context "$ctx" >/dev/null
    echo
    echo "    function $name() internal pure returns (Vector memory v) {"
    echo "        v.pk = hex\"$(hex "$W/$name.pk")\";"
    echo "        v.message = hex\"$(hex "$W/$name.msg")\";"
    echo "        v.ctx = hex\"$(hex "$W/$name.ctx")\";"
    echo "        v.sig = hex\"$(hex "$W/$name.sig")\";"
    echo "    }"
  done
  echo "}"
} > "$OUT"
echo "wrote $OUT (${#CASES[@]} vectors)"
