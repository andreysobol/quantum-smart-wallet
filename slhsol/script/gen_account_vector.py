#!/usr/bin/env python3
"""Reproduce the test-only raw-digest SLH fixture with the repository's Rust CLI."""
import argparse
import hashlib
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
CONTEXT = "QuantumSmartWallet/SLH-DSA-SHA2-128s/v1"
DIGEST = hashlib.sha256(b"QuantumAccount native envelope fixture v1").digest()
# Public deterministic fixture seeds. Never use the resulting key for funds.
SEED = bytes(range(48)).hex()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--rslh", type=Path, default=ROOT.parent / "rslh/target/release/rslh")
    args = parser.parse_args()
    binary = args.rslh.resolve(strict=True)
    (ROOT / "cache").mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="account-vector-", dir=ROOT / "cache") as temp:
        directory = Path(temp)
        secret, public, message, signature = [directory / n for n in ("key", "pub", "msg", "sig")]
        message.write_bytes(DIGEST)

        def run(*arguments):
            subprocess.run([str(binary), *map(str, arguments)], check=True, capture_output=True)

        run("keygen", "--seed", SEED, "--sk", secret, "--pk", public)
        run("sign", "--sk", secret, "--in", message, "--sig", signature,
            "--context", CONTEXT, "--deterministic")
        run("verify", "--pk", public, "--in", message, "--sig", signature, "--context", CONTEXT)
        key = public.read_text().strip().split(":", 1)[1]
        witness = signature.read_bytes()
        assert len(bytes.fromhex(key)) == 32 and len(witness) == 7856
        fixture = (
            "// SPDX-License-Identifier: MIT\n"
            "// Generated by script/gen_account_vector.py. Public test key only.\n"
            "pragma solidity ^0.8.24;\n\n"
            "library AccountVector {\n"
            f'    bytes32 internal constant PUBLIC_KEY = hex"{key}";\n'
            f'    bytes32 internal constant DIGEST = hex"{DIGEST.hex()}";\n'
            f'    bytes internal constant CONTEXT = "{CONTEXT}";\n\n'
            "    function signature() internal pure returns (bytes memory) {\n"
            f'        return hex"{witness.hex()}";\n'
            "    }\n}\n"
        )
        destination = ROOT / "test/AccountVector.sol"
        destination.write_text(fixture)
        subprocess.run(["forge", "fmt", str(destination)], check=True, capture_output=True)
        print(f"Generated {destination.name}: 32-byte digest, {len(witness)}-byte signature")


if __name__ == "__main__":
    main()
